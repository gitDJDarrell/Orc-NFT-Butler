/**
 * A very small software rasterizer: enough to draw the floor/volume chart
 * (filled rects, lines, points, and text) into an RGB buffer, with no native
 * dependencies. See png.ts for why we don't use a real canvas library.
 */

export interface Rgb {
  r: number;
  g: number;
  b: number;
}

export function rgb(hex: number): Rgb {
  return { r: (hex >> 16) & 0xff, g: (hex >> 8) & 0xff, b: hex & 0xff };
}

