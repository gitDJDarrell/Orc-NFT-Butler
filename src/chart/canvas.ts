const GLYPH_WIDTH = 5;
const GLYPH_HEIGHT = 7;
const GLYPH_SPACING = 1;

export class Canvas {
  readonly width: number;
  readonly height: number;
  private readonly buf: Uint8Array;

  constructor(width: number, height: number, background: Rgb) {
    this.width = width;
    this.height = height;
    this.buf = new Uint8Array(width * height * 3);
    this.clear(background);
  }

  clear(color: Rgb): void {
    for (let i = 0; i < this.width * this.height; i++) {
      this.buf[i * 3] = color.r;
      this.buf[i * 3 + 1] = color.g;
      this.buf[i * 3 + 2] = color.b;
    }
  }

  setPixel(x: number, y: number, color: Rgb): void {
    const px = Math.round(x);
    const py = Math.round(y);
    if (px < 0 || py < 0 || px >= this.width || py >= this.height) return;
    const i = (py * this.width + px) * 3;
    this.buf[i] = color.r;
    this.buf[i + 1] = color.g;
    this.buf[i + 2] = color.b;
  }

  fillRect(x: number, y: number, w: number, h: number, color: Rgb): void {
    const x0 = Math.max(0, Math.round(x));
    const y0 = Math.max(0, Math.round(y));
    const x1 = Math.min(this.width, Math.round(x + w));
    const y1 = Math.min(this.height, Math.round(y + h));
    for (let py = y0; py < y1; py++) {
      for (let px = x0; px < x1; px++) {
        const i = (py * this.width + px) * 3;
        this.buf[i] = color.r;
        this.buf[i + 1] = color.g;
        this.buf[i + 2] = color.b;
      }
    }
  }

  /** Bresenham, thickened by drawing a square of `thickness` at each step. */
  line(x0: number, y0: number, x1: number, y1: number, color: Rgb, thickness = 1): void {
    let cx = Math.round(x0);
    let cy = Math.round(y0);
    const tx = Math.round(x1);
    const ty = Math.round(y1);
    const dx = Math.abs(tx - cx);
    const dy = -Math.abs(ty - cy);
    const sx = cx < tx ? 1 : -1;
    const sy = cy < ty ? 1 : -1;
    let err = dx + dy;
    const half = Math.floor(thickness / 2);

    // Guard against a pathological input producing an unbounded loop.
    for (let guard = 0; guard < 10_000; guard++) {
      if (thickness <= 1) this.setPixel(cx, cy, color);
      else this.fillRect(cx - half, cy - half, thickness, thickness, color);

      if (cx === tx && cy === ty) return;
      const e2 = 2 * err;
      if (e2 >= dy) {
        err += dy;
        cx += sx;
      }
      if (e2 <= dx) {
        err += dx;
        cy += sy;
      }
    }
  }

  /** Dotted horizontal rule, for gridlines. */
  dottedHLine(x0: number, x1: number, y: number, color: Rgb, on = 2, off = 4): void {
    for (let x = Math.round(x0); x < Math.round(x1); x++) {
      if ((x - Math.round(x0)) % (on + off) < on) this.setPixel(x, y, color);
    }
  }

  /** Draws text at integer `scale`. Characters outside the font range render as blanks rather than throwing. */
  text(x: number, y: number, value: string, color: Rgb, scale = 1): void {
    let cursorX = Math.round(x);
    const cursorY = Math.round(y);

    for (const char of value) {
      const code = char.charCodeAt(0);
      const glyph = FONT[code - FONT_FIRST_CHAR];
      if (glyph) {
        for (let col = 0; col < GLYPH_WIDTH; col++) {
          const bits = glyph[col]!;
          for (let row = 0; row < GLYPH_HEIGHT; row++) {
            if (bits & (1 << row)) {
              if (scale === 1) this.setPixel(cursorX + col, cursorY + row, color);
              else this.fillRect(cursorX + col * scale, cursorY + row * scale, scale, scale, color);
            }
          }
        }
      }
      cursorX += (GLYPH_WIDTH + GLYPH_SPACING) * scale;
    }
  }

  /** Rendered pixel width of `value` at `scale` — for right-aligning and centering. */
  static textWidth(value: string, scale = 1): number {
    return value.length > 0 ? (value.length * (GLYPH_WIDTH + GLYPH_SPACING) - GLYPH_SPACING) * scale : 0;
  }

  static get glyphHeight(): number {
    return GLYPH_HEIGHT;
  }

  toPng(): Buffer {
    return encodePng(this.buf, this.width, this.height);
  }
}
